create policy course_contents_select_entitled
on public.course_contents for select
to authenticated
using (
  exists (
    select 1
    from public.courses c
    join public.profiles p on p.id = (select auth.uid())
    where c.id = course_contents.course_id
      and p.is_active
      and (c.is_published or p.role = 'admin')
      and (not c.is_member_only or p.is_member or p.role = 'admin')
  )
);

