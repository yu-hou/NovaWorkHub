create or replace function public.increment_course_views_internal(target_course_id bigint)
returns bigint
language sql
security invoker
set search_path = ''
as $$
  update public.courses
  set views = views + 1
  where id = target_course_id
  returning views;
$$;

revoke all on function public.increment_course_views_internal(bigint) from public, anon, authenticated;
grant execute on function public.increment_course_views_internal(bigint) to service_role;

