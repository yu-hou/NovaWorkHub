create schema if not exists private;
revoke all on schema private from public;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  display_name text not null default '',
  role text not null default 'user' check (role in ('user', 'admin')),
  is_member boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(btrim(name)) between 1 and 64),
  color_class text not null default 'category-gold' check (
    color_class in (
      'category-gold', 'category-rose', 'category-violet',
      'category-cyan', 'category-green', 'category-slate'
    )
  ),
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.courses (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete restrict,
  title text not null check (length(btrim(title)) between 1 and 255),
  summary text not null default '',
  cover text not null default '',
  learners integer not null default 0 check (learners >= 0),
  views bigint not null default 0 check (views >= 0),
  is_member_only boolean not null default false,
  is_published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.course_contents (
  course_id bigint primary key references public.courses(id) on delete cascade,
  feishu_doc_url text not null check (length(btrim(feishu_doc_url)) between 8 and 1024),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index courses_category_id_idx on public.courses(category_id);
create index courses_published_sort_idx
  on public.courses(sort_order, id) where is_published;
create index profiles_role_idx on public.profiles(role) where role = 'admin';

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

